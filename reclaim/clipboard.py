"""Clipboard history: what to keep, what to skip, and for how long.

The platform layer (clipboard_mac) feeds a Watcher through a small adapter,
so everything here runs and is tested without AppKit.
"""
import hashlib
import os
import threading
import time

from . import paths, store

DB_FILE = os.path.join(paths.DATA_DIR, "clipboard.db")

SCHEMA = """
CREATE TABLE IF NOT EXISTS clips (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  at REAL NOT NULL,
  kind TEXT NOT NULL,            -- text | files | image
  text TEXT,                     -- text, or newline-separated paths
  data BLOB,                     -- PNG for images
  bytes INTEGER NOT NULL,
  app TEXT,
  pinned INTEGER NOT NULL DEFAULT 0,
  digest TEXT NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_clips_at ON clips(pinned DESC, at DESC);
"""

# Types password managers and well-behaved apps set on things that must not
# be recorded. See nspasteboard.org.
SECRET_TYPES = {
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
}
DEFAULT_IGNORE_APPS = ["1Password", "Bitwarden", "Keychain Access", "Passwords",
                       "LastPass", "Dashlane", "KeePassXC", "Enpass"]
MAX_TEXT = 200_000
MAX_IMAGE = 5 * 1024 * 1024


# Virtual key codes on a US layout; the hotkey letter is matched by key code
# so it keeps working with other keyboard layouts selected.
KEYCODES = dict(zip("asdfhgzxcv", range(10)), b=11, q=12, w=13, e=14, r=15,
                y=16, t=17, o=31, u=32, i=34, p=35, l=37, j=38, k=40, n=45, m=46)
MODS = {"shift": 1 << 17, "ctrl": 1 << 18, "control": 1 << 18,
        "alt": 1 << 19, "option": 1 << 19, "opt": 1 << 19,
        "cmd": 1 << 20, "command": 1 << 20}
MOD_MASK = (1 << 17) | (1 << 18) | (1 << 19) | (1 << 20)


def parse_hotkey(spec):
    """'ctrl+cmd+v' -> (keycode, modifier flags), or None if unusable."""
    parts = [p.strip().lower() for p in (spec or "").split("+") if p.strip()]
    if not parts or parts[-1] not in KEYCODES:
        return None
    flags = 0
    for p in parts[:-1]:
        if p not in MODS:
            return None
        flags |= MODS[p]
    if not flags & (MODS["cmd"] | MODS["ctrl"] | MODS["alt"]):
        return None                      # a bare letter would fire while typing
    return KEYCODES[parts[-1]], flags


def connect():
    paths.ensure_dirs()
    db = store.Database(DB_FILE, SCHEMA)
    db.raw                      # create the file now, with private permissions
    return db


def _digest(kind, payload):
    h = hashlib.blake2b(digest_size=16)
    h.update(kind.encode())
    h.update(payload if isinstance(payload, bytes) else payload.encode("utf-8", "replace"))
    return h.hexdigest()


def add(con, kind, text=None, data=None, app=None, now=None):
    """Record a clip, or move an identical one back to the top. Returns id."""
    now = now or time.time()
    payload = data if kind == "image" else (text or "")
    if not payload:
        return None
    dg = _digest(kind, payload)
    row = con.execute("SELECT id FROM clips WHERE digest = ?", (dg,)).fetchone()
    if row:
        con.execute("UPDATE clips SET at = ?, app = COALESCE(?, app) WHERE id = ?",
                    (now, app, row["id"]))
        con.commit()
        return row["id"]
    size = len(data) if data else len((text or "").encode("utf-8", "replace"))
    cur = con.execute("INSERT INTO clips (at, kind, text, data, bytes, app, digest) "
                      "VALUES (?,?,?,?,?,?,?)", (now, kind, text, data, size, app, dg))
    con.commit()
    return cur.lastrowid


def prune(con, max_items=500, days=30, max_images=50, now=None):
    """Drop old, unpinned clips. Pinned clips are kept forever."""
    now = now or time.time()
    con.execute("DELETE FROM clips WHERE pinned = 0 AND at < ?", (now - days * 86400,))
    con.execute("DELETE FROM clips WHERE pinned = 0 AND kind = 'image' AND id NOT IN "
                "(SELECT id FROM clips WHERE pinned = 0 AND kind = 'image' "
                "ORDER BY at DESC LIMIT ?)", (max_images,))
    con.execute("DELETE FROM clips WHERE pinned = 0 AND id NOT IN "
                "(SELECT id FROM clips WHERE pinned = 0 ORDER BY at DESC LIMIT ?)",
                (max_items,))
    con.commit()


def recent(con, limit=50, query=None):
    q = "SELECT id, at, kind, substr(text, 1, 2000) AS text, bytes, app, pinned FROM clips"
    args = []
    if query:
        q += " WHERE text LIKE ? ESCAPE '\\'"
        args.append("%" + query.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%")
    q += " ORDER BY pinned DESC, at DESC LIMIT ?"
    args.append(limit)
    return [dict(r) for r in con.execute(q, args)]


def get(con, clip_id):
    r = con.execute("SELECT * FROM clips WHERE id = ?", (clip_id,)).fetchone()
    return dict(r) if r else None


def set_pinned(con, clip_id, pinned):
    con.execute("UPDATE clips SET pinned = ? WHERE id = ?", (1 if pinned else 0, clip_id))
    con.commit()


def delete(con, clip_id):
    con.execute("DELETE FROM clips WHERE id = ?", (clip_id,))
    con.commit()


def clear(con, keep_pinned=True):
    con.execute("DELETE FROM clips" + (" WHERE pinned = 0" if keep_pinned else ""))
    con.commit()
    con.execute("VACUUM")


def title(clip, width=60):
    """One line for a menu."""
    if clip["kind"] == "image":
        return "Image (%d KB)" % max(1, clip["bytes"] // 1024)
    text = (clip.get("text") or "").strip()
    if clip["kind"] == "files":
        names = [os.path.basename(p) for p in text.splitlines() if p]
        text = ", ".join(names) if len(names) < 4 else "%s and %d more" % (names[0], len(names) - 1)
    text = " ".join(text.split())
    return text if len(text) <= width else text[:width - 1] + "…"


class Watcher:
    """Polls a pasteboard adapter and records what changes.

    The adapter provides: change_count(), types(), string(), file_paths(),
    image_png(), frontmost_app(). All of it is called from one thread.
    """

    def __init__(self, adapter, cfg, con=None):
        self.pb = adapter
        self._cfg = cfg                  # a dict, or a function returning the live one
        self.con = con or connect()
        self.last = adapter.change_count()
        self.ignore_next = None          # change count of our own writes
        self.pending = []                # clip ids the UI asked us to copy
        self._lock = threading.Lock()
        self.last_prune = 0

    @property
    def cfg(self):
        return self._cfg() if callable(self._cfg) else self._cfg

    def enabled(self):
        return self.cfg.get("clipboard", True) and not self.cfg.get("clipboard_paused")

    def request_copy(self, clip_id):
        with self._lock:
            self.pending.append(clip_id)

    def poll(self):
        """Call often (twice a second). Returns the new clip id, if any."""
        with self._lock:
            pending, self.pending = self.pending, []
        for cid in pending:
            self.copy(cid)
        n = self.pb.change_count()
        if n == self.last:
            return None
        self.last = n
        if n == self.ignore_next or not self.enabled():
            return None
        new = self._capture()
        if time.time() - self.last_prune > 3600:
            self.last_prune = time.time()
            prune(self.con, self.cfg.get("clipboard_max_items", 500),
                  self.cfg.get("clipboard_days", 30))
        return new

    def _capture(self):
        types = set(self.pb.types() or ())
        if types & SECRET_TYPES:
            return None
        app = self.pb.frontmost_app()
        ignore = self.cfg.get("clipboard_ignore_apps", DEFAULT_IGNORE_APPS)
        if app and any(app.lower() == a.lower() for a in ignore):
            return None
        files = self.pb.file_paths()
        if files:
            return add(self.con, "files", text="\n".join(files), app=app)
        text = self.pb.string()
        if text and text.strip():
            if len(text) > MAX_TEXT:
                return None
            return add(self.con, "text", text=text, app=app)
        png = self.pb.image_png()
        if png and len(png) <= MAX_IMAGE:
            return add(self.con, "image", data=png, app=app)
        return None

    def copy(self, clip_id):
        """Put a clip back on the pasteboard without recording it again."""
        clip = get(self.con, clip_id)
        if not clip:
            return False
        if clip["kind"] == "image":
            self.pb.write(png=clip["data"])
        elif clip["kind"] == "files":
            self.pb.write(files=[p for p in (clip["text"] or "").splitlines() if p])
        else:
            self.pb.write(text=clip["text"])
        self.ignore_next = self.last = self.pb.change_count()
        add(self.con, clip["kind"], text=clip["text"], data=clip["data"])  # to the top
        return True
